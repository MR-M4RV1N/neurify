    private function renderParagraphs(string $text, string $class = 'insight-paragraph'): string
    {
        $text = trim($text);
        if ($text === '') {
            return '';
        }

        // Безопасно экранируем
        $safe = htmlspecialchars($text, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');

        // Разбиваем на абзацы по пустой строке (2+ переводов строк)
        $parts = preg_split("/\R{2,}/u", $safe) ?: [];
        $parts = array_values(array_filter(array_map('trim', $parts), static function ($p) {
            return $p !== '';
        }));
        if (!$parts) {
            return '';
        }

        // Одинарные переносы внутри абзаца оставляем как <br>
        $parts = array_map(static function ($p) {
            return nl2br($p);
        }, $parts);

        return '<div class="insight-text">' .
            implode('', array_map(static function ($p) use ($class) {
                return '<p class="' . $class . '">' . $p . '</p>';
            }, $parts)) .
            '</div>';
    }
