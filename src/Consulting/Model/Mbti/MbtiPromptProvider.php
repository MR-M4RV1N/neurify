    public function buildUserPrompt(\DateTimeImmutable $weekStart, string $weekText, string $mbtiStyle, string $lang): string
    {
        $weekEnd = $weekStart->modify('+6 days');

        $languageLine = 'Язык: русский';
        if ($lang === 'lv') {
            $languageLine = 'Valoda: latviešu';
        } elseif ($lang === 'en') {
            $languageLine = 'Language: English';
        }

        return <<<PROMPT
Проанализируй записи за неделю через стиль мышления "{$mbtiStyle}". Опирайся ТОЛЬКО на текст дневника.

ФОРМАТ (СТРОГО):
- rating: число 0–10 — насколько неделя прожита в стиле "{$mbtiStyle}".
- rating_reason: одно предложение — почему поставил именно эту оценку, на что ориентировался.
- what_liked: список, ровно 3 пункта — что понравилось в этой неделе в стиле "{$mbtiStyle}".
- missing_notes: список, ровно 3 пункта — каких записей/смыслов не хватает, чтобы лучше раскрыть стиль "{$mbtiStyle}".
- small_questions: список, ровно 3 пункта — маленькие вопросы, на которые полезно ответить на следующей неделе.
- recommendations: ЕДИНСТВЕННЫЙ список, ровно 3 пункта — это МАЛЕНЬКИЕ ШАГИ.
  Каждый пункт: действие + когда/условие + критерий успеха.
- summary: 1 абзац (3–5 предложений), сжато, без руминации и морали.

ПЕРИОД: {$weekStart->format('Y-m-d')} — {$weekEnd->format('Y-m-d')}

ДНЕВНИК:
{$weekText}

ВЕРНИ ТОЛЬКО валидный JSON строго по этой схеме:
{
  "mbti_style": "{$mbtiStyle}",
  "rating": 0,
  "what_liked": [],
  "missing_notes": [],
  "small_questions": [],
  "recommendations": [],
  "summary": ""
}

{$languageLine}
PROMPT;
    }

    private function getTePrompt(string $base): string
    {
        return <<<PROMPT
{$base}

Ты — аналитик с доминантным экстравертным мышлением (Te).
Te видит не намерения — а выходы. Не процесс — а то, что реально
сдвинулось в внешнем мире и можно измерить или проверить.
Твоя задача: найти в записях, где действия производили реальный
измеримый результат, и где энергия уходила в активность без выхода.

Te-линза конкретно:
- Где в записях есть конкретный результат: что-то сделано, измерено, завершено?
- Где действие было эффективным — минимум усилий, максимум выхода?
- Где усилие было, но результат не зафиксирован или неясен?
- Где система или процесс работали на человека, а где он работал вместо системы?

СТРОГО СОБЛЮДАЙ JSON-СХЕМУ:

rating (0–10):
  Оценивай соотношение реальных результатов к затраченным усилиям.
